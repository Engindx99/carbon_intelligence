"""Write the Ansys Mechanical script that names the calciner's boundary
faces and sets its mesh sizes.

Workbench drops the STEP's face colours, so the named selections are
found the way calciner.bas finds the faces: each boundary is the planar
face whose centroid and area are the source's (geometry/plant_geometry.py).
Nothing here is typed by hand; rerun after a geometry change.

    python3 tools/calciner_named_selections.py

writes geometry/output/2500/calciner_named_selections.py; in Mechanical
(Meshing): Automation > Scripting > Open Script > Run.
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from geometry import plant_geometry as pg  # noqa: E402

OUT = ROOT / "geometry" / "output" / "2500" / "calciner_named_selections.py"

# Mesh sizes, m (CFD decisions, user 14 Oct 2026): global tet sized to
# the Student node limit (C4: 155 mm on 674 m3 gave 1.015M nodes); the
# small pipes get their own face size so a few cells cross them.
GLOBAL_SIZE = 0.210
FACE_SIZES = {"fuel_inlet": 0.080, "meal_feed": 0.080}

TEMPLATE = '''# Generated by tools/calciner_named_selections.py -- do not edit.
# Names the calciner's boundary faces by centroid and area (SI, m) and
# sets the mesh sizes. Run in Mechanical: Automation > Scripting.
import math

TARGETS = {targets}
GLOBAL_SIZE = {global_size}
FACE_SIZES = {face_sizes}
# the feed pipes' side faces: outside the vessel radius, between the feed levels (m);
# their own zone so the DPM can let particles that drift into the dead-end pipes escape
PIPE_BAND = {pipe_band}
TOL = 0.02
# Mechanical's face Area is a faceted one: a small circle comes out ~2.5 % short (the edge lengths
# are exact), so the area only has to be near; the centroid pins the face
AREA_TOL = 0.05

body = DataModel.GeoData.Assemblies[0].Parts[0].Bodies[0]
faces = list(body.Faces)

def match(scale):
    found = {{}}
    for name, (c, area, d) in TARGETS.items():
        hits = []
        for f in faces:
            fc = [x * scale for x in f.Centroid]
            fa = f.Area * scale * scale
            if (math.sqrt(sum((fc[i] - c[i]) ** 2 for i in range(3))) < TOL * d
                    and abs(fa - area) < AREA_TOL * area):
                hits.append(f)
        if len(hits) != 1:
            return None, "%s: %d faces match" % (name, len(hits))
        found[name] = hits[0]
    return found, ""

# GeoData speaks the CAD's length unit; the STEP is in mm.
found, why = None, ""
for scale in (1.0, 1.0e-3):
    found, why = match(scale)
    if found:
        break
if not found:
    raise Exception("calciner faces not found (" + why + ")")

def selection(ids):
    s = ExtAPI.SelectionManager.CreateSelectionInfo(SelectionTypeEnum.GeometryEntities)
    s.Ids = ids
    return s

def named(name, ids):
    ns = Model.AddNamedSelection()
    ns.Name = name
    ns.Location = selection(ids)
    return ns

for name in sorted(found):
    named(name, [found[name].Id])
taken = set(f.Id for f in found.values())
R_VESSEL, Z_LO, Z_HI = PIPE_BAND
def in_pipe_band(f):
    c = [x * scale for x in f.Centroid]
    return math.hypot(c[0], c[1]) > R_VESSEL and Z_LO < c[2] < Z_HI
pipes = [f.Id for f in faces if f.Id not in taken and in_pipe_band(f)]
if len(pipes) < 4:
    raise Exception("feed pipe side faces: %d found, at least 4 expected" % len(pipes))
named("pipe_wall", pipes)
taken |= set(pipes)
named("wall", [f.Id for f in faces if f.Id not in taken])

mesh = Model.Mesh
# adaptive sizing ignores ElementSize (a batch run gave 129k elements instead of ~800k)
mesh.UseAdaptiveSizing = False
mesh.ElementSize = Quantity(GLOBAL_SIZE, "m")
for prefix, size in FACE_SIZES.items():
    ids = [found[n].Id for n in found if n.startswith(prefix)]
    sizing = mesh.AddSizing()
    sizing.Location = selection(ids)
    sizing.ElementSize = Quantity(size, "m")

print("calciner: %d boundary faces named, %d pipe wall faces, %d wall faces; global %g m, %s" % (
    len(found), len(pipes), len(faces) - len(taken), GLOBAL_SIZE, FACE_SIZES))
'''


def targets(g):
    """Each boundary: (centroid, area, a length its tolerance scales on)."""
    cal, gn, inl = pg.calciner(g), pg.gooseneck(g), pg.calciner_inlets(g)
    ta, meal, fuel = inl["tertiary_air"], inl["meal"], inl["fuel"]
    r_leg = 0.5 * gn["D_leg"]
    leg_area = math.pi * r_leg * r_leg
    (xm, zm), (yf, zf) = meal["end"], fuel["end"]
    return {
        "kiln_gas_inlet": ((0.0, 0.0, 0.0), math.pi * cal["r_throat"] ** 2, cal["D_throat"]),
        "gas_outlet_1": ((gn["x_leg"], -gn["y_off"], gn["z_end"]), leg_area, gn["D_leg"]),
        "gas_outlet_2": ((-gn["x_leg"], -gn["y_off"], gn["z_end"]), leg_area, gn["D_leg"]),
        "tertiary_air_inlet": (ta["centre"], ta["end_area"], ta["D"]),
        "meal_feed_1": ((xm, 0.0, zm), meal["end_area"], meal["D"]),
        "meal_feed_2": ((-xm, 0.0, zm), meal["end_area"], meal["D"]),
        "fuel_inlet_1": ((0.0, yf, zf), fuel["end_area"], fuel["D"]),
        "fuel_inlet_2": ((0.0, -yf, zf), fuel["end_area"], fuel["D"]),
    }


def pipe_band(g):
    """(vessel radius, z low, z high): the feed pipes' side faces lie outside
    the radius and between the lowest pipe hole and the highest pipe end."""
    inl = pg.calciner_inlets(g)
    meal, fuel = inl["meal"], inl["fuel"]
    z_lo = min(meal["hole_bottom"], fuel["hole_bottom"]) - 0.5 * fuel["D"]
    z_hi = max(meal["end"][1], fuel["end"][1]) + meal["D"]
    return (round(pg.calciner(g)["R"], 6), round(z_lo, 6), round(z_hi, 6))


def render(g):
    t = {k: (tuple(round(x, 6) for x in c), round(a, 6), round(d, 6))
         for k, (c, a, d) in targets(g).items()}
    lines = "{\n" + "".join("    %r: %r,\n" % (k, t[k]) for k in sorted(t)) + "}"
    return TEMPLATE.format(targets=lines, global_size=GLOBAL_SIZE,
                           face_sizes=repr(FACE_SIZES), pipe_band=repr(pipe_band(g)))


if __name__ == "__main__":
    OUT.write_text(render(pg.load()), newline="\r\n")
    print("wrote", OUT.relative_to(ROOT))
